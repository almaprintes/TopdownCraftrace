import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {iosDesynchronizedContext,IOS_WEBGL_SYNC_KEY} from '../src/game/performance/iosWebglPresentationMode.js';
const empty={getItem:()=>null};
const synced={getItem:key=>key===IOS_WEBGL_SYNC_KEY?'1':null};
const desynced={getItem:key=>key===IOS_WEBGL_SYNC_KEY?'0':null};
assert.equal(iosDesynchronizedContext({isIos:true,isProd:false,storage:empty}),true,'DEV default must preserve existing iOS desynchronized mode');
assert.equal(iosDesynchronizedContext({isIos:true,isProd:false,storage:synced}),false,'DEV toggle must request normal WebGL synchronization');
assert.equal(iosDesynchronizedContext({isIos:true,isProd:false,storage:desynced}),true,'A/B reverse must restore baseline');
assert.equal(iosDesynchronizedContext({isIos:true,isProd:true,storage:synced}),true,'Google Play/production must ignore DEV toggle');
assert.equal(iosDesynchronizedContext({isIos:false,isProd:false,storage:desynced}),false,'other platforms must retain existing context flag');
const game=readFileSync('src/game/game.js','utf8');
const diag=readFileSync('src/game/dev/iosRaceFrameDiagnostics.js','utf8');
assert.match(game,/desynchronized:iosWebglDesync,roundPixels:safeMode/);
assert.match(game,/if\(!IS_PROD_BUILD&&!isIOSDevice\(\)&&!\/Android\/i\.test/,'avoid duplicate always-on FPS RAF on DEV iOS');
assert.match(game,/window\.__tdrIosFrameConfig=\{preset:vp\.preset,renderResolution:vp\.renderResolution,targetFps,frameLimit,forceSetTimeOut,safeMode,webglDesyncRequested:iosWebglDesync\}/);
assert.match(diag,/PROBAR WEBGL SYNC \(REINICIA\)/);
assert.match(diag,/VOLVER WEBGL DESYNC \(REINICIA\)/);
assert.match(diag,/localStorage\.setItem\(IOS_WEBGL_SYNC_KEY,requested\?'1':'0'\);window\.location\.reload\(\)/);
assert.match(diag,/getContextAttributes\?\.\(\)/);
assert.match(diag,/frameInfo\(scene\)/);
console.log('PASS: iOS WebGL context sync A/B with unchanged production; on-device pacing diagnostics; no duplicate FPS RAF');
