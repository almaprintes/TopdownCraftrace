import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createIosFramePhaseStats,recordIosFramePhase,formatIosFramePhaseStats } from '../src/game/performance/iosFramePhaseStats.js';
const data=createIosFramePhaseStats();
assert.equal(recordIosFramePhase(data,0,11,20),false,'first frame has no prior POST_RENDER');
assert.equal(recordIosFramePhase(data,100,90,115),false,'reject reversed ordering');
assert.equal(recordIosFramePhase(data,100,101,1700),false,'reject background-sized gap');
assert.equal(recordIosFramePhase(data,100,117,119),true);
assert.equal(recordIosFramePhase(data,119,180,181),true);
assert.equal(recordIosFramePhase(data,181,188,272),true);
assert.equal(recordIosFramePhase(data,272,300,320),true);
assert.equal(data.count,4);
assert.equal(data.over33Inter,1,'one >33ms interval dominated by between cycles');
assert.equal(data.over33Cycle,1,'one >33ms interval dominated by Phaser cycle');
assert.equal(data.over33Mixed,1,'one >33ms mixed interval');
assert.equal(data.spikes.length,2);
assert.deepEqual(data.spikes.map(x=>Math.round(x.total)),[91,62]);
const report=formatIosFramePhaseStats(data);
assert.match(report,/ENTRE CICLOS/);
assert.match(report,/DENTRO CICLO/);
assert.match(report,/DESGLOSE entre\/dentro\/mixto 1\/1\/1/);
assert.match(report,/NO mide GPU/);
assert.equal(formatIosFramePhaseStats(createIosFramePhaseStats()),'FASES CICLO: SIN MUESTRAS EMPAREJADAS');
const diag=readFileSync(new URL('../src/game/dev/iosRaceFrameDiagnostics.js',import.meta.url),'utf8');
assert.match(diag,/phaseEnabled:!IS_PROD_BUILD&&\/iPhone\/i/);
assert.match(diag,/state\.frameBegin=state\.stepStart/);
assert.match(diag,/if\(state\.phaseEnabled\)recordIosFramePhase/);
assert.match(diag,/state\.frameBegin=0;state\.stepStart=0/);
assert.match(diag,/formatIosFramePhaseStats\(w\.phases\)/);
assert.doesNotMatch(diag,/requestAnimationFrame\(/,'must not add diagnostic RAF');
console.log('iPhone DEV inter-cycle versus Phaser-cycle profiler OK; no RAF, production or Android instrumentation');
