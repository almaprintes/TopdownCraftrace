import fs from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const __dirname=path.dirname(fileURLToPath(import.meta.url));
const ROOT=path.resolve(__dirname,'..');
const TRACKS_ROOT=path.join(ROOT,'public/assets/tracks');
const OUT=path.join(ROOT,'src/game/tracks/trackBeautyLayers.generated.js');

async function exists(p){try{await fs.access(p);return true;}catch{return false;}}
async function readPublishedManifests(){
  const entries=[];
  if(!await exists(TRACKS_ROOT))return entries;
  for(const dir of await fs.readdir(TRACKS_ROOT,{withFileTypes:true})){
    if(!dir.isDirectory())continue;
    const manifestPath=path.join(TRACKS_ROOT,dir.name,'beauty','manifest.json');
    if(!await exists(manifestPath))continue;
    try{
      const m=JSON.parse(await fs.readFile(manifestPath,'utf8'));
      if(!m?.trackKey||!Array.isArray(m.tiles)||m.tiles.length===0)continue;
      const beautyDir=path.dirname(manifestPath);
      const complete=(await Promise.all(m.tiles.map(t=>exists(path.join(beautyDir,t.file))))).every(Boolean);
      if(!complete){console.warn(`[beauty-catalog] skipping incomplete ${m.trackKey}`);continue;}
      entries.push(m);
    }catch(err){console.warn(`[beauty-catalog] invalid ${manifestPath}: ${err.message}`);}
  }
  return entries.sort((a,b)=>String(a.trackKey).localeCompare(String(b.trackKey)));
}

function jsBoolObject(o={}){return `{ ${Object.entries(o).map(([k,v])=>`${k}:${!!v}`).join(', ')} }`;}
function render(entries){
  const blocks=entries.map(m=>{
    const rev=String(m.revision||`beauty-v${m.version||1}`);
    const tiles=m.tiles.map((t,i)=>`      Object.freeze({ key:${JSON.stringify(`beauty-${m.trackKey}-${i}`)}, path:${JSON.stringify(`assets/tracks/${m.trackKey}/beauty/${t.file}?v=${rev}`)}, x:${Number(t.x)}, y:${Number(t.y)}, w:${Number(t.w)}, h:${Number(t.h)} }),`).join('\n');
    return `  ${JSON.stringify(m.trackKey)}: Object.freeze({\n    useBeautyLayer: true,\n    assetRevision: ${JSON.stringify(rev)},\n    assetsAvailable: true,\n    worldW: ${Number(m.worldW)}, worldH: ${Number(m.worldH)}, depth: ${Number(m.depth??9)},\n    replaces: Object.freeze(${jsBoolObject(m.replaces)}),\n    tiles: Object.freeze([\n${tiles}\n    ])\n  })`;
  });
  return `// AUTO-GENERATED by scripts/build-track-beauty-catalog.mjs.\n// Source of truth: published public/assets/tracks/*/beauty/manifest.json files.\nexport const GENERATED_TRACK_BEAUTY_LAYERS = Object.freeze({\n${blocks.join(',\n')}\n});\n`;
}

const entries=await readPublishedManifests();
await fs.writeFile(OUT,render(entries));
console.log(`[beauty-catalog] wrote ${entries.length} track(s)`);
