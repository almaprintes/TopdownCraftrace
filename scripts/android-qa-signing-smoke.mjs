import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const gradle=readFileSync('android/app/build.gradle','utf8');
const wf=readFileSync('.github/workflows/android-revenuecat-qa-apk.yml','utf8');
const code=readFileSync('index.html','utf8');
const qa=gradle.match(/deviceTest\s*\{([\s\S]*?)\n\s*\}/)?.[1]||'';
const baseline=gradle.match(/defaultConfig\s*\{([\s\S]*?)\n\s*\}/)?.[1]||'';
assert.match(baseline,/applicationId "com\.craftracestudio\.topdownrace"/);
assert.match(baseline,/versionCode 8\b/,'public Play versionCode must not change');
assert.match(baseline,/versionName "1\.1\.188"/,'public Play versionName must not change');
assert.match(qa,/applicationIdSuffix '\.rewardedtest'/,'same QA package identity');
assert.match(qa,/versionCode 1000317/,'QA versionCode must increase from 8 without affecting Play');
assert.match(qa,/versionName '1\.2\.317-qa'/);
assert.match(wf,/actions\/cache@v4/,'CI signing key reuse, not per-run regeneration');
assert.match(wf,/tdr-rewardedtest-debug-signing-v1/,'stable cache identity');
assert.match(wf,/if test ! -s "\$HOME\/\.android\/debug\.keystore"/,'no signer overwrite if restored');
assert.match(wf,/keytool -genkeypair/);
assert.match(wf,/androiddebugkey/,'use standard debug signing config');
assert.match(wf,/TDR_CI_BRIDGE_TEST: '1'/);
assert.match(wf,/apksigner" verify --verbose --print-certs/,'APK signer verification');
assert.match(wf,/versionCode='1000317'/,'validate installed version, not just source');
assert.match(wf,/tdr-qa-1\.2\.317/,'deliver fresh tag, never clobber prior APK');
assert.match(wf,/TDR-QA-DEV-1\.2\.317-REAL-ADS-SIN-MEDIR\.apk/);
assert.match(code,/content="DEV 1\.2\.317"/);
console.log('PASS: immutable public version, stable QA app ID, monotonically increasing QA version, cached QA signing and verified direct-download APK.');
