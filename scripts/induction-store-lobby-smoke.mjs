import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const telemetry=readFileSync('src/game/seasons/seasonTelemetry.js','utf8');
const economy=readFileSync('src/game/store/storeEconomy.js','utf8');
const events=readFileSync('src/game/events/raceEvents.js','utf8');
const lobby=readFileSync('src/game/ui/LobbyDomUi.js','utf8');
const polish=readFileSync('src/game/ui/LobbyPublishPolish.js','utf8');
assert.match(events,/\{id:'store-buy',[\s\S]*?objective:\{type:'storeBuys',target:1/,'Induction mission 7 is successful store purchase');
assert.match(economy,/saveGarage\(s\); recordStoreBuy\(\); return \{ok:true/,'Only successful pack purchases advance mission 7');
assert.match(telemetry,/const saved=save\(s\);[\s\S]*?window\.dispatchEvent\(new CustomEvent\('tdr:seasonProgressChanged',\{detail:\{kind:'storeBuys'\}\}\)\)/,'Persist event progress before notifying lobby');
assert.match(lobby,/window\.addEventListener\('tdr:seasonProgressChanged',syncSeasonCard\)/);
assert.match(lobby,/window\.removeEventListener\('tdr:seasonProgressChanged',syncSeasonCard\)/,'No accumulating event listeners across sessions');
assert.match(lobby,/renderDomCards\(scene,root,true\)/,'Only refresh season card after purchase');
assert.match(lobby,/function renderDomCards\(scene, root, seasonOnly=false\)/);
assert.match(lobby,/if\(seasonOnly\)return;/,'Do not reload car artwork or track previews on purchase');
assert.match(lobby,/polishSeasonCard\(scene,root\.querySelector\('\[data-event-card\]'\)\)/,'Restore season card navigation and claim marker after update');
assert.match(polish,/export function polishSeasonCard\(scene,season\)/);
assert.match(lobby,/renderDomCards\(scene,root\); return root/,'Standard lobby initial load unaffected');
console.log('PASS: induction 7 store purchase updates lobby in place with preserved pass navigation, no polling or duplicated listener');
