import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {liveV2ErrorMessage} from '../src/game/ui/craftraceLiveV2ErrorMessage.js';
const inFuture=new Date(Date.now()+2*60*60*1000).toISOString().replace(/\.\d{3}Z$/,'Z');
const translated=liveV2ErrorMessage({message:'Room creation limit',details:'retry_at_utc='+inFuture});
assert.match(translated,/Has alcanzado el límite temporal de creación de pistas/);
assert.match(translated,/Podrás crear otra a partir de las \d\d:\d\d/);
assert.ok(!translated.includes('Room creation limit'));
assert.match(liveV2ErrorMessage({message:'Room creation limit'}),/Prueba de nuevo más tarde/);
assert.match(liveV2ErrorMessage({message:'Room creation limit',details:'retry_at_utc=bad'}),/Prueba de nuevo más tarde/);
assert.equal(liveV2ErrorMessage({message:'Otro fallo'}),'Otro fallo');
assert.equal(liveV2ErrorMessage(null),'Error al comunicar con la pista');
const client=readFileSync('src/game/online/craftraceLiveV2LobbyClient.js','utf8');
const lobby=readFileSync('src/game/ui/craftraceLiveV2Lobby.js','utf8');
assert.ok(client.includes('error.details=body?.details||null'));
assert.ok(client.includes('error.hint=body?.hint||null'));
assert.ok(lobby.includes('say(liveV2ErrorMessage(e))'));
assert.ok(lobby.includes("import {liveV2ErrorMessage} from './craftraceLiveV2ErrorMessage.js'"));
console.log('PASS LIVE 4 room-creation limit: Spanish translation, exact server unlock time, fallback and RPC metadata.');
