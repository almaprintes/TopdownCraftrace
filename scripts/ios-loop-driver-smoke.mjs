import assert from 'node:assert/strict';
import fs from 'node:fs';
import {resolveIosDevLoopDriver,IOS_DEV_TIMEOUT_KEY} from '../src/game/performance/iosDevLoopDriver.js';
const blank={getItem:()=>null},enabled={getItem:k=>k===IOS_DEV_TIMEOUT_KEY?'1':null};
const args={isIphone:true,isProd:false,safeMode:false,forceRaf:false};
assert.deepEqual(resolveIosDevLoopDriver({...args,storage:blank}),{forceSetTimeOut:false,mode:'RAF'},'Existing iPhone baseline is RAF');
assert.deepEqual(resolveIosDevLoopDriver({...args,storage:enabled}),{forceSetTimeOut:true,mode:'TIMEOUT'},'DEV iPhone timeout trial');
assert.deepEqual(resolveIosDevLoopDriver({...args,isProd:true,storage:enabled}),{forceSetTimeOut:false,mode:'RAF'},'Production untouched');
assert.deepEqual(resolveIosDevLoopDriver({...args,isIphone:false,storage:enabled}),{forceSetTimeOut:false,mode:'RAF'},'Android/iPad/desktop untouched');
assert.deepEqual(resolveIosDevLoopDriver({...args,safeMode:true,storage:enabled}),{forceSetTimeOut:true,mode:'SAFE TIMEOUT'},'Safe mode continues existing fallback');
assert.deepEqual(resolveIosDevLoopDriver({...args,safeMode:true,forceRaf:true,storage:enabled}),{forceSetTimeOut:false,mode:'SAFE RAF'},'Existing safe-mode manual override');
assert.equal(resolveIosDevLoopDriver({...args,storage:{getItem(){throw Error('blocked');}}}).forceSetTimeOut,false);
const game=fs.readFileSync('src/game/game.js','utf8');
const panel=fs.readFileSync('src/game/dev/iosRaceFrameDiagnostics.js','utf8');
const stability=fs.readFileSync('scripts/stability-smoke.mjs','utf8');
assert.match(game,/const loopTrial=resolveIosDevLoopDriver\(\{isIphone:/);
assert.match(game,/isProd:IS_PROD_BUILD,safeMode,forceRaf:forceRafLoop\(\),storage:localStorage/);
assert.match(game,/const forceSetTimeOut=loopTrial.forceSetTimeOut/);
assert.match(game,/window\.__tdrIosFrameConfig\.loopTrialMode=loopTrial\.mode/);
assert.match(panel,/LOOP \$\{conf\.loopTrialMode/);
assert.match(panel,/if\(!IS_PROD_BUILD&&isIos\(\)\)/,'Loop toggle must be inside DEV-only diagnostic controls');
assert.match(panel,/if\(\/iPhone\/i\.test\(String\(navigator\?\.userAgent\|\|''\)\)&&!window\.__tdrIosFrameConfig\?\.safeMode\)/);
assert.match(panel,/PROBAR LOOP TIMEOUT \(REINICIA\)/);
assert.match(panel,/VOLVER LOOP RAF \(REINICIA\)/);
assert.match(panel,/localStorage\.removeItem\(IOS_DEV_TIMEOUT_KEY\)/);
assert.match(panel,/localStorage\.setItem\(IOS_DEV_TIMEOUT_KEY,'1'\)/);
assert.match(stability,/const loopTrial=resolveIosDevLoopDriver/);
console.log('PASS: iPhone DEV-only Phaser loop A/B, production+Android untouched, safe-mode override intact');
