import assert from 'node:assert/strict';
import {readFileSync,existsSync} from 'node:fs';
import {CAR_SPECS} from '../src/game/cars/carSpecs.js';
import {equipCarSkin} from '../src/game/skins/carSkins.js';
import {carVisualCandidates} from '../src/game/skins/carDisplayArt.js';
import {carCardFile,carCardUrl} from '../src/game/cars/carCardArt.js';
const id='crown_cuper',spec=CAR_SPECS[id],card=carCardFile(id,spec);
assert.equal(card,'card_crown_cuper_raro_018.svg');
assert.equal(carCardFile('crown_axis',CAR_SPECS.crown_axis),'card_crown_axis_poco_comun_004.webp');
assert.ok(existsSync('public/assets/cars/runtime/'+card));
const svg=readFileSync('public/assets/cars/runtime/'+card,'utf8');
assert.match(svg,/<svg\b/);
assert.match(svg,/data:image\/webp;base64,UklGR/);
assert.match(svg,/width="1024" height="1536"/,'same card dimensions as CROWN Vector');
const sourceCard=readFileSync('public/assets/cars/runtime/card_crown_vector_raro_005.webp').toString('base64');
const originalCar=readFileSync('public/assets/skins/skin_crown_cuper_original.webp').toString('base64');
assert.ok(svg.includes(sourceCard),'Cuper card must reuse authentic CROWN card template');
assert.ok(svg.includes(originalCar),'Cuper collection card must use unchanged base original car');
assert.match(svg,/#018 · Raro/);
assert.match(svg,/>64<\/text>/);
assert.match(svg,/>61<\/text>/);
assert.match(svg,/>72<\/text>/);
assert.match(svg,/>63<\/text>/);
assert.match(svg,/>66<\/text>/);
assert.match(svg,/CUPER/);
assert.doesNotMatch(svg,/skin_crown_cuper_gold/);
const storageData=new Map(),storage={getItem:key=>storageData.get(key)||null,setItem:(key,v)=>storageData.set(key,v)};
const fixed=carCardUrl(id,spec,'/TopdownCraftrace/dev/');
assert.equal(fixed,'/TopdownCraftrace/dev/assets/cars/runtime/'+card+'?v=1');
assert.equal(carVisualCandidates(id,spec,{base:'/dev/',storage,dev:true})[0],'/dev/assets/skins/skin_crown_cuper_original.webp');
assert.equal(equipCarSkin(id,'gold',{storage,dev:true}).ok,true);
assert.equal(carVisualCandidates(id,spec,{base:'/dev/',storage,dev:true})[0],'/dev/assets/skins/skin_crown_cuper_gold.webp');
assert.equal(carCardUrl(id,spec,'/TopdownCraftrace/dev/'),fixed,'Card is immutable');
assert.equal(carVisualCandidates(id,spec,{base:'/dev/',storage,dev:false})[0],'/dev/assets/skins/skin_crown_cuper_original.webp');
const garage=readFileSync('src/game/scenes/GarageLazyCardsScene.js','utf8');
assert.match(garage,/skinPreview=\(id,spec\)=>carCardUrl\(id,spec,BASE\)/);
assert.doesNotMatch(garage,/thumb\.src=skinPreview/);
const phaser=readFileSync('src/game/scenes/GarageScene.js','utf8');
assert.match(phaser,/const src=carCardUrl\(carId,spec\)/);
assert.match(phaser,/const url=carCardUrl\(carId,spec\)/);
assert.doesNotMatch(phaser,/hasAlternativeSkins/);
assert.match(readFileSync('src/game/scenes/StatsMasteryScene.js','utf8'),/applyStatsCarArt\(img,carId\)/);
assert.match(readFileSync('src/game/scenes/StatsScene.js','utf8'),/carVisualCandidates\(r\.id,r\.spec/);
assert.match(readFileSync('src/game/ui/raceLoadingExperienceV3.js','utf8'),/applyCarVisual\(root\.querySelector\('\[data-car-image\]'\)/);
console.log('Cuper: fixed base card, selected skin in stats and pre-race, fallbacks and DEV gate OK');
